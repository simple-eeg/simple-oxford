function handles = local_down_arrow(ax, x, top, bottom, color)
handles = gobjects(2, 1);
handles(1) = line(ax, [x x], [top bottom+0.018], ...
    'Color', color, 'LineWidth', 0.9);
handles(2) = patch(ax, [x-0.015 x+0.015 x], ...
    [bottom+0.028 bottom+0.028 bottom], color, 'EdgeColor', color);
end

function handles = local_count_bar(ax, y, label, counts, x, scale, h, config)
