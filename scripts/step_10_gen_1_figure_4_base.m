function local_validate_pdf(path)
info = dir(path);
if isempty(info) || info.bytes < 1000
    error('SimpleOxford:Figure4Base:InvalidPDF', ...
        'The exported PDF is missing or unexpectedly small.');
end
[fileID, message] = fopen(path, 'rb');
if fileID < 0
    error('SimpleOxford:Figure4Base:UnreadablePDF', ...
        'Could not read exported PDF: %s', message);
end
cleanup = onCleanup(@() fclose(fileID));
header = fread(fileID, 5, '*char')';
if ~strcmp(header, '%PDF-')
    error('SimpleOxford:Figure4Base:InvalidPDFHeader', ...
        'The exported file does not have a PDF header.');
end
clear cleanup;
end
