    'Position', [x y-h/2 retainedWidth h], ...
    'FaceColor', config.color.retained, ...
    'EdgeColor', config.color.published, 'LineWidth', 0.4);
handles.excluded = rectangle(ax, ...
    'Position', [x+retainedWidth y-h/2 excludedWidth h], ...
    'FaceColor', config.color.excluded, ...
    'EdgeColor', config.color.published, 'LineWidth', 0.4);
handles.retainedText = text(ax, x+retainedWidth/2, y, sprintf('%d', retained), ...
    'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle', ...
    'Color', 'w', 'FontName', config.font.name, ...
    'FontSize', config.font.smallSize, 'FontWeight', 'bold');
if excludedWidth >= 5
    textX = x+retainedWidth+excludedWidth/2; alignment = 'center';
else
    textX = x+retainedWidth+excludedWidth+1.2; alignment = 'left';
end
handles.excludedText = text(ax, textX, y, sprintf('%d', excluded), ...
    'HorizontalAlignment', alignment, 'VerticalAlignment', 'middle', ...
    'FontName', config.font.name, 'FontSize', config.font.smallSize, ...
    'Color', config.color.line);
end

