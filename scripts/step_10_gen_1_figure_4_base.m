%% Local functions
function panelData = local_read_panel_data(config)
required = {'subjectID', 'trial_arm', 'HL_ER_nNRF_mag', ...
    'HL_ER_nNRF_mag_Screening', 'HL_ER_nNRF_mag_pub', ...
    'HL_ER_nNRF_mag_pub_Screening'};
opts = detectImportOptions(config.paths.csv, ...
    'PreserveVariableNames', true, 'TextType', 'string');
opts.VariableNamingRule = 'preserve';
if any(strcmp(opts.VariableNames, 'subjectID'))
    opts = setvartype(opts, 'subjectID', 'string');
end
T = readtable(config.paths.csv, opts);
missing = setdiff(required, T.Properties.VariableNames, 'stable');
if ~isempty(missing)
    error('SimpleOxford:Figure4Base:MissingColumns', ...
        'Missing required CSV column(s): %s', strjoin(missing, ', '));
end

id = local_text(T.subjectID);
arm = local_text(T.trial_arm);
simpleStatus = local_text(T.HL_ER_nNRF_mag_Screening);
publishedStatus = local_text(T.HL_ER_nNRF_mag_pub_Screening);
simpleMagnitude = local_numeric(T.HL_ER_nNRF_mag, 'HL_ER_nNRF_mag');
publishedMagnitude = local_numeric(T.HL_ER_nNRF_mag_pub, ...
    'HL_ER_nNRF_mag_pub');
if any(id == "") || numel(unique(id)) ~= height(T)
    error('SimpleOxford:Figure4Base:InvalidSubjectID', ...
        'subjectID values must be nonblank and unique.');
end
if height(T) ~= config.expected.nTimeLockedEEG
    error('SimpleOxford:Figure4Base:UnexpectedPopulation', ...
        'Expected %d CSV rows but found %d.', ...
        config.expected.nTimeLockedEEG, height(T));
end
local_categories(arm, config.expected.arms, 'trial_arm');
local_categories(simpleStatus, ["Included"; "Excluded"], ...
    'HL_ER_nNRF_mag_Screening');
local_categories(publishedStatus, ["Included"; "Excluded"], ...
    'HL_ER_nNRF_mag_pub_Screening');

simpleIncluded = simpleStatus == "Included";
publishedIncluded = publishedStatus == "Included";
if ~isequal(simpleIncluded, isfinite(simpleMagnitude)) || ...
        ~isequal(publishedIncluded, isfinite(publishedMagnitude))
    error('SimpleOxford:Figure4Base:StatusMagnitudeMismatch', ...
        'Retained-set status does not match later-NRF availability.');
end
if any(publishedIncluded & ~simpleIncluded)
    error('SimpleOxford:Figure4Base:NestingFailure', ...
        'The published set is not nested within the SIMPLE-retained set.');
end

nCSV = height(T);
nSimple = sum(simpleIncluded);
nPublished = sum(publishedIncluded);
nSimpleExcluded = nCSV - nSimple;
nPublishedExcluded = nCSV - nPublished;
observed = [nCSV nSimple nPublished nSimpleExcluded nPublishedExcluded];
expected = [config.expected.nTimeLockedEEG ...
    config.expected.nSimpleRetained config.expected.nPublishedRetained ...
    config.expected.nSimpleExcluded config.expected.nPublishedExcluded];
if ~isequal(observed, expected)
    error('SimpleOxford:Figure4Base:UnexpectedCounts', ...
        'CSV-derived retained-set counts differ from the accepted values.');
end

simpleByArm = zeros(2, 2); publishedByArm = zeros(2, 2);
for armIndex = 1:2
    inArm = arm == config.expected.arms(armIndex);
    simpleByArm(armIndex, :) = [sum(inArm & simpleIncluded), ...
        sum(inArm & ~simpleIncluded)];
    publishedByArm(armIndex, :) = [sum(inArm & publishedIncluded), ...
        sum(inArm & ~publishedIncluded)];
end
if ~isequal(simpleByArm, config.expected.simpleByArm) || ...
        ~isequal(publishedByArm, config.expected.publishedByArm)
    error('SimpleOxford:Figure4Base:UnexpectedArmCounts', ...
        'CSV-derived retained/excluded counts by arm are unexpected.');
end
if sum(simpleByArm, 'all') ~= nCSV || sum(publishedByArm, 'all') ~= nCSV
    error('SimpleOxford:Figure4Base:IncompleteArmCounts', ...
        'Trial-arm counts do not recover the full CSV population.');
end

nUnavailable = config.study.nRandomised - nCSV;
if nUnavailable < 0
    error('SimpleOxford:Figure4Base:InvalidRandomisedPopulation', ...
        'The randomised population is smaller than the CSV population.');
end
panelData.A = struct('nRandomised', config.study.nRandomised, ...
    'nTimeLockedEEG', nCSV, 'nUnavailable', nUnavailable, ...
    'nSimpleRetained', nSimple, 'nPublishedRetained', nPublished, ...
    'nSimpleExcluded', nSimpleExcluded, ...
    'nPublishedExcluded', nPublishedExcluded, ...
    'simpleLossPercent', 100*nSimpleExcluded/config.study.nRandomised, ...
    'publishedLossPercent', 100*nPublishedExcluded/config.study.nRandomised, ...
    'publishedNestedWithinSimple', true);
panelData.B = struct('arms', config.expected.arms, ...
    'simple', simpleByArm, 'published', publishedByArm);
panelData.C = config.jasp.treatment;
panelData.D = struct('status', 'Blank for manual JASP export');
panelData.E = struct('status', 'Blank for manual JASP export');
end

function values = local_text(raw)
values = strtrim(string(raw(:)));
values(ismissing(values)) = "";
end

function values = local_numeric(raw, name)
if isnumeric(raw)
    values = double(raw(:));
else
    textValues = strtrim(string(raw(:)));
    missing = ismissing(textValues) | textValues == "" | ...
        strcmpi(textValues, "NaN");
    values = str2double(textValues);
    if any(~missing & isnan(values))
        error('SimpleOxford:Figure4Base:NonNumericValue', ...
            'Column %s contains a nonnumeric value.', name);
    end
end
if any(isinf(values))
    error('SimpleOxford:Figure4Base:InfiniteValue', ...
        'Column %s contains an infinite value.', name);
end
end

function local_categories(values, expected, name)
if ~isequal(sort(unique(values)), sort(string(expected(:))))
    error('SimpleOxford:Figure4Base:UnexpectedCategories', ...
        'Column %s does not contain exactly the expected categories.', name);
end
end

function pathOut = local_canonical(pathIn)
