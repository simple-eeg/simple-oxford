function helperFiles = local_assert_helper_paths(functionsDir, helperNames)
canonicalFunctionsDir = char(java.io.File(functionsDir).getCanonicalPath());
helperFiles = cell(size(helperNames));
for helperIndex = 1:numel(helperNames)
    helperName = helperNames{helperIndex};
    expectedPath = fullfile(canonicalFunctionsDir, [helperName, '.m']);
    local_assert_exact_path(which(helperName), expectedPath, helperName);
    helperFiles{helperIndex} = expectedPath;
end
end

function local_assert_exact_path(resolvedPath, expectedPath, routeName)
if isempty(resolvedPath) || ~isfile(expectedPath)
    error('SimpleOxford:Step81:MissingLocalHelper', ...
        'Required local route is missing or unresolved: %s.', routeName);
end
resolvedPath = char(java.io.File(resolvedPath).getCanonicalPath());
expectedPath = char(java.io.File(expectedPath).getCanonicalPath());
if ~strcmp(resolvedPath, expectedPath)
    error('SimpleOxford:Step81:ShadowedLocalHelper', ...
        'Expected %s at %s, but it resolved to %s.', ...
        routeName, expectedPath, resolvedPath);
end
end

function tf = local_canonical_equal(firstPath, secondPath)
firstPath = char(java.io.File(firstPath).getCanonicalPath());
secondPath = char(java.io.File(secondPath).getCanonicalPath());
tf = strcmp(firstPath, secondPath);
end

function tf = local_is_canonical_child(parentPath, childPath)
parentPath = string(char(java.io.File(parentPath).getCanonicalPath()));
childPath = string(char(java.io.File(childPath).getCanonicalPath()));
tf = startsWith(childPath, parentPath + string(filesep));
end

