%% step_8_gen_1_check_plots.m
% Create Figure 3: Post-core guardrails in the Petal dataset.
%
% The figure contains eight fixed recording-level panels:
%   rows 1--3: mean time series, time-frequency and PSD checks for
%               lance_prestim (left) and lance (right);
%   row 4:      the saved QC (left) and NRF (right) paired-separation checks.
%
% Inputs
%   data/summary/screening/pooled_screened_eeg_epochs.mat
%   data/summary/screening/step_7_check_6_sep_check_qc_result.mat
%   data/summary/screening/step_7_check_7_sep_check_nrf_result.mat
%
% Outputs
%   data/results/figure_3_post_core_guardrails_in_the_petal_dataset.pdf
%   data/logs/step_8_gen_1_check_plots.log
%
% The script leaves figure3Config, figure3PanelData, figure3PanelHandles and
% figure3Figure in the base workspace for inspection. It does not rerun a
% Step 7 script or recalculate either saved paired-separation result.

log_command_window('start');
clear; clc;

%% Fixed transaction state
baseDir = '/Users/lukebaxter/Developer/simple-eeg/simple-oxford';
scriptsDir = fullfile(baseDir, 'scripts');
functionsDir = fullfile(baseDir, 'functions');
resultsDir = fullfile(baseDir, 'data', 'results');
screeningDir = fullfile(baseDir, 'data', 'summary', 'screening');

figure3PdfName = 'figure_3_post_core_guardrails_in_the_petal_dataset.pdf';
figure3FinalPdf = fullfile(resultsDir, figure3PdfName);
figure3PartialPdf = fullfile(resultsDir, ...
    'figure_3_post_core_guardrails_in_the_petal_dataset.partial.pdf');
figure3RollbackPdf = fullfile(resultsDir, ...
    'figure_3_post_core_guardrails_in_the_petal_dataset.rollback.pdf');
figure3LogPath = fullfile(baseDir, 'data', 'logs', ...
    'step_8_gen_1_check_plots.log');

figure3LogActive = true;
figure3LogStopAttempted = false;
figure3Figure = gobjects(0);
figure3ResultsDirCreated = false;
figure3HadPriorFinal = false;
figure3RollbackReady = false;
figure3PdfPromoted = false;

% Empty in the production source. Isolated temporary-fixture copies may
% replace this literal to exercise deterministic transaction failures.
figure3InternalFailpoint = "";

try
    %% Local path and dependency preflight
    if ~isfolder(baseDir) || ~isfolder(scriptsDir) || ~isfolder(functionsDir)
        error('SimpleOxford:Step81:MissingRepository', ...
            'The configured Oxford repository or one of its source folders is missing.');
    end
    if ~local_canonical_equal(pwd, scriptsDir)
        error('SimpleOxford:Step81:WrongCurrentFolder', ...
            'Run this script with the MATLAB current folder set to %s.', scriptsDir);
    end

    addpath(functionsDir, '-begin');
    clear NRFUtils collect_guardrail_event_series ...
        plot_guardrail_average_ts plot_guardrail_average_tf ...
        plot_guardrail_average_psd load_guardrail_separation_result ...
        plot_paired_effect_result ts_average_simple ts_nrf_overlay
    rehash toolboxcache;

    requiredLocalHelpers = { ...
        'NRFUtils', ...
        'collect_guardrail_event_series', ...
        'plot_guardrail_average_ts', ...
        'plot_guardrail_average_tf', ...
        'plot_guardrail_average_psd', ...
        'load_guardrail_separation_result', ...
        'plot_paired_effect_result', ...
        'ts_average_simple', ...
        'ts_nrf_overlay'};
    local_assert_helper_paths(functionsDir, requiredLocalHelpers);
    local_assert_exact_path(which('log_command_window'), ...
        fullfile(scriptsDir, 'log_command_window.m'), 'log_command_window');

    requiredToolboxRoutes = {'cwtfilterbank','cwt','pmtm','corr','fitlm'};
    for routeIndex = 1:numel(requiredToolboxRoutes)
        routeName = requiredToolboxRoutes{routeIndex};
        resolvedRoute = which(routeName);
        if isempty(resolvedRoute)
            error('SimpleOxford:Step81:MissingDependency', ...
                'Required MATLAB dependency did not resolve: %s.', routeName);
        end
        isBuiltInRoute = startsWith(resolvedRoute, 'built-in', ...
            'IgnoreCase', true);
        if ~isBuiltInRoute && ...
                ~local_is_canonical_child(matlabroot, resolvedRoute)
            error('SimpleOxford:Step81:ShadowedDependency', ...
                '%s must resolve to MATLAB, but resolved to %s.', ...
                routeName, resolvedRoute);
        end
    end

    validFailpoints = ["", "after-rollback", "after-promotion", "after-log-stop"];
    if ~isscalar(figure3InternalFailpoint) || ...
            ~ismember(figure3InternalFailpoint, validFailpoints)
        error('SimpleOxford:Step81:InvalidInternalFailpoint', ...
            'The internal transaction failpoint is invalid.');
    end

    %% Fixed Oxford scientific and presentation configuration
    figure3Config = struct();
    figure3Config.paths = struct( ...
        'base_dir', baseDir, ...
        'functions_dir', functionsDir, ...
        'screening_dir', screeningDir, ...
        'screened_epochs_mat', fullfile(screeningDir, ...
            'pooled_screened_eeg_epochs.mat'), ...
        'qc_result_mat', fullfile(screeningDir, ...
            'step_7_check_6_sep_check_qc_result.mat'), ...
        'nrf_result_mat', fullfile(screeningDir, ...
            'step_7_check_7_sep_check_nrf_result.mat'), ...
        'final_pdf', figure3FinalPdf, ...
        'partial_pdf', figure3PartialPdf, ...
        'rollback_pdf', figure3RollbackPdf, ...
        'log', figure3LogPath);
    figure3Config.channel = "CZ";
    figure3Config.events = struct( ...
        'ordered', ["lance_prestim", "lance"], ...
        'reference', "lance_prestim", ...
        'true', "lance");
    figure3Config.use_exclusion_flags = true;

    [earlyNRFName, earlyNRFFile] = NRFUtils.resolveTemplateFile( ...
        'early_NRF_500Hz', baseDir);
    [noxiousNRFName, noxiousNRFFile] = NRFUtils.resolveTemplateFile( ...
        'noxious_NRF_500Hz', baseDir);
    figure3Config.templates = struct( ...
        'early_name', earlyNRFName, ...
        'early_file', earlyNRFFile, ...
        'noxious_name', noxiousNRFName, ...
        'noxious_file', noxiousNRFFile);

    overlays = repmat(struct( ...
        'name', '', 'template_file', '', 'fit_time_ms', NaN, ...
        'jitter_ms', NaN, 'colour', [], 'display_label', ''), 2, 1);
    overlays(1) = struct( ...
        'name', earlyNRFName, ...
        'template_file', earlyNRFFile, ...
        'fit_time_ms', 100, ...
        'jitter_ms', 100, ...
        'colour', [20 204 204] / 255, ...
        'display_label', earlyNRFName);
    overlays(2) = struct( ...
        'name', noxiousNRFName, ...
        'template_file', noxiousNRFFile, ...
        'fit_time_ms', 400, ...
        'jitter_ms', 100, ...
        'colour', [1 0 0], ...
        'display_label', noxiousNRFName);

    axisFontSize = 8;
    panelLineWidth = 2;
    timeZeroColour = [0.6 0.6 0.6];
    figure3Config.time_series = struct( ...
        'aggregator', "mean", ...
        'smoothing_ms', 0, ...
        'overlays', overlays, ...
        'x_limits_ms', [-100 950], ...
        'y_limits_uV', [-20 20], ...
        'time_zero_colour', timeZeroColour, ...
        'axis_font_size', axisFontSize, ...
        'line_width', panelLineWidth, ...
        'legend_location', "northeast");
    figure3Config.time_frequency = struct( ...
        'voices_per_octave', 12, ...
        'baseline_time_agg', "mean", ...
        'epoch_agg', "mean", ...
        'y_axis_scale', "linear", ...
        'time_limits_ms', [-100 950], ...
        'frequency_limits_hz', [3 30], ...
        'colour_limits_db', [-4 4], ...
        'time_zero_colour', timeZeroColour, ...
        'axis_font_size', axisFontSize);
    figure3Config.psd = struct( ...
        'epoch_window', "post-stim", ...
        'aggregator', "mean", ...
        'aggregate_domain', "linear_power", ...
        'frequency_limits_hz', [-1 251], ...
        'axis_font_size', axisFontSize, ...
        'line_width', panelLineWidth, ...
        'time_bandwidth_product', 4, ...
        'nfft', 1024);

    pairedSourcePaths = struct( ...
        'compute_helper', fullfile(functionsDir, 'compute_paired_effect.m'), ...
        'plot_helper', fullfile(functionsDir, 'plot_paired_effect_result.m'), ...
        'save_helper', fullfile(functionsDir, 'save_paired_separation_result.m'));
    qcSourcePaths = pairedSourcePaths;
    qcSourcePaths.input_csv = fullfile(screeningDir, ...
        'pooled_screened_eeg_qc_features.csv');
    qcSourcePaths.script = fullfile(scriptsDir, ...
        'step_7_check_6_sep_check_qc.m');
    nrfSourcePaths = pairedSourcePaths;
    nrfSourcePaths.input_csv = fullfile(screeningDir, ...
        'pooled_screened_eeg_nrf_features.csv');
    nrfSourcePaths.script = fullfile(scriptsDir, ...
        'step_7_check_7_sep_check_nrf.m');
    figure3Config.separation = struct( ...
        'alpha', 0.05, ...
        'qc_expected', struct( ...
            'channel', "Cz", ...
            'reference_event', "lance_prestim", ...
            'true_event', "lance", ...
            'metric', "MeanAbsDiffNorm", ...
            'nrf_name', "", ...
            'use_exclusion_flags', true, ...
            'source_paths', qcSourcePaths), ...
        'nrf_expected', struct( ...
            'channel', "Cz", ...
            'reference_event', "lance_prestim", ...
            'true_event', "lance", ...
            'metric', "fglsCoef", ...
            'nrf_name', "noxious_NRF_500Hz", ...
            'use_exclusion_flags', true, ...
            'source_paths', nrfSourcePaths));

    axesPositions = [ ...
        0.07 0.75 0.34 0.15; ...
        0.56 0.75 0.34 0.15; ...
        0.07 0.54 0.30 0.15; ...
        0.56 0.54 0.30 0.15; ...
        0.07 0.34 0.34 0.15; ...
        0.56 0.34 0.34 0.15; ...
        0.07 0.05 0.34 0.15; ...
        0.56 0.05 0.34 0.15];
    colourbarPositions = [ ...
        0.385 0.54 0.012 0.15; ...
        0.875 0.54 0.012 0.15];
    labelPositions = struct( ...
        'part_a', [0.04 0.965 0.92 0.025], ...
        'reference', [0.07 0.925 0.34 0.025], ...
        'true', [0.56 0.925 0.34 0.025], ...
        'part_b', [0.04 0.270 0.92 0.025], ...
        'qc', [0.07 0.225 0.34 0.025], ...
        'nrf', [0.56 0.225 0.34 0.025]);
    figure3Config.presentation = struct( ...
        'figure_position_cm', [2 2 18 24], ...
        'axes_positions', axesPositions, ...
        'colourbar_positions', colourbarPositions, ...
        'label_positions', labelPositions, ...
        'axis_font_size', axisFontSize, ...
        'part_label_font_size', 10, ...
        'column_label_font_size', 9);
    figure3Config.labels = struct( ...
        'part_a', 'A. Time and frequency domain checks', ...
        'reference', 'Internal reference (lance_prestim)', ...
        'true', 'True event (lance)', ...
        'part_b', 'B. Feature separation checks', ...
        'qc', 'QC feature (MeanAbsDiffNorm)', ...
        'nrf', 'Later noxious NRF magnitude');

    inputPaths = {figure3Config.paths.screened_epochs_mat, ...
        figure3Config.paths.qc_result_mat, figure3Config.paths.nrf_result_mat};
    for inputIndex = 1:numel(inputPaths)
        if ~isfile(inputPaths{inputIndex})
            error('SimpleOxford:Step81:MissingInput', ...
                'Required Step 8.1 input is missing: %s.', inputPaths{inputIndex});
        end
        if ~local_is_canonical_child(baseDir, inputPaths{inputIndex})
            error('SimpleOxford:Step81:NonLocalInput', ...
                'Step 8.1 input must remain inside the Oxford repository: %s.', ...
                inputPaths{inputIndex});
        end
    end
    outputPaths = {figure3FinalPdf, figure3PartialPdf, figure3RollbackPdf};
    for outputIndex = 1:numel(outputPaths)
        if ~local_is_canonical_child(baseDir, outputPaths{outputIndex})
            error('SimpleOxford:Step81:NonLocalOutput', ...
                'Step 8.1 output must remain inside the Oxford repository: %s.', ...
                outputPaths{outputIndex});
        end
    end

    %% One screened-epoch load and validated saved row-4 inputs
    epochInput = load(figure3Config.paths.screened_epochs_mat, 'epochs_pooled');
    if ~isfield(epochInput, 'epochs_pooled')
        error('SimpleOxford:Step81:MissingEpochVariable', ...
            'Expected variable epochs_pooled in %s.', ...
            figure3Config.paths.screened_epochs_mat);
    end
    epochs_pooled = epochInput.epochs_pooled;
    clear epochInput;

    seriesByEvent = collect_guardrail_event_series(epochs_pooled, ...
        figure3Config.channel, figure3Config.events.ordered, ...
        figure3Config.use_exclusion_flags);
    clear epochs_pooled;

    qcSeparation = load_guardrail_separation_result( ...
        figure3Config.paths.qc_result_mat, ...
        figure3Config.separation.qc_expected);
    nrfSeparation = load_guardrail_separation_result( ...
        figure3Config.paths.nrf_result_mat, ...
        figure3Config.separation.nrf_expected);

    %% Draw the fixed four-by-two panel layout
    figure3Figure = figure( ...
        'Name', 'Figure 3: Post-core guardrails in the Petal dataset', ...
        'NumberTitle', 'off', ...
        'Visible', 'off', ...
        'Color', 'w', ...
        'Units', 'centimeters', ...
        'Position', figure3Config.presentation.figure_position_cm, ...
        'PaperPositionMode', 'auto');

    dataAxes = gobjects(8, 1);
    for axesIndex = 1:8
        dataAxes(axesIndex) = axes(figure3Figure, ...
            'Units', 'normalized', ...
            'Position', figure3Config.presentation.axes_positions(axesIndex, :));
    end

    [tsReference, tsReferenceHandles] = plot_guardrail_average_ts( ...
        dataAxes(1), seriesByEvent(1), figure3Config.time_series);
    set(dataAxes(1), 'Tag', 'figure3-ts-reference');
    [tsTrue, tsTrueHandles] = plot_guardrail_average_ts( ...
        dataAxes(2), seriesByEvent(2), figure3Config.time_series);
    set(dataAxes(2), 'Tag', 'figure3-ts-true');

    [tfReference, tfReferenceHandles] = plot_guardrail_average_tf( ...
        dataAxes(3), seriesByEvent(1), figure3Config.time_frequency);
    set(dataAxes(3), 'Tag', 'figure3-tf-reference', 'Units', 'normalized', ...
        'Position', figure3Config.presentation.axes_positions(3, :));
    set(tfReferenceHandles.colorbar, 'Units', 'normalized', ...
        'Position', figure3Config.presentation.colourbar_positions(1, :));
    [tfTrue, tfTrueHandles] = plot_guardrail_average_tf( ...
        dataAxes(4), seriesByEvent(2), figure3Config.time_frequency);
    set(dataAxes(4), 'Tag', 'figure3-tf-true', 'Units', 'normalized', ...
        'Position', figure3Config.presentation.axes_positions(4, :));
    set(tfTrueHandles.colorbar, 'Units', 'normalized', ...
        'Position', figure3Config.presentation.colourbar_positions(2, :));

    [psdReference, psdReferenceHandles] = plot_guardrail_average_psd( ...
        dataAxes(5), seriesByEvent(1), figure3Config.psd);
    set(dataAxes(5), 'Tag', 'figure3-psd-reference');
    [psdTrue, psdTrueHandles] = plot_guardrail_average_psd( ...
        dataAxes(6), seriesByEvent(2), figure3Config.psd);
    set(dataAxes(6), 'Tag', 'figure3-psd-true');

    qcPairs = qcSeparation.pairing_table;
    qcSeparationHandles = plot_paired_effect_result(dataAxes(7), ...
        qcPairs.true_value, qcPairs.reference_value, qcSeparation.estimate, ...
        figure3Config.events.true, figure3Config.events.reference, ...
        qcSeparation.settings.effect_specification, ...
        figure3Config.separation.alpha);
    title(dataAxes(7), '');
    set(dataAxes(7), 'Tag', 'figure3-qc-separation', ...
        'FontSize', figure3Config.presentation.axis_font_size);

    nrfPairs = nrfSeparation.pairing_table;
    nrfSeparationHandles = plot_paired_effect_result(dataAxes(8), ...
        nrfPairs.true_value, nrfPairs.reference_value, nrfSeparation.estimate, ...
        figure3Config.events.true, figure3Config.events.reference, ...
        nrfSeparation.settings.effect_specification, ...
        figure3Config.separation.alpha);
    title(dataAxes(8), '');
    set(dataAxes(8), 'Tag', 'figure3-nrf-separation', ...
        'FontSize', figure3Config.presentation.axis_font_size);

    labelHandles = struct();
    labelHandles.part_a = local_figure_label(figure3Figure, ...
        figure3Config.presentation.label_positions.part_a, ...
        figure3Config.labels.part_a, 'figure3-label-part-a', 'left', ...
        figure3Config.presentation.part_label_font_size);
    labelHandles.reference = local_figure_label(figure3Figure, ...
        figure3Config.presentation.label_positions.reference, ...
        figure3Config.labels.reference, 'figure3-label-reference', 'center', ...
        figure3Config.presentation.column_label_font_size);
    labelHandles.true = local_figure_label(figure3Figure, ...
        figure3Config.presentation.label_positions.true, ...
        figure3Config.labels.true, 'figure3-label-true', 'center', ...
        figure3Config.presentation.column_label_font_size);
    labelHandles.part_b = local_figure_label(figure3Figure, ...
        figure3Config.presentation.label_positions.part_b, ...
        figure3Config.labels.part_b, 'figure3-label-part-b', 'left', ...
        figure3Config.presentation.part_label_font_size);
    labelHandles.qc = local_figure_label(figure3Figure, ...
        figure3Config.presentation.label_positions.qc, ...
        figure3Config.labels.qc, 'figure3-label-qc', 'center', ...
        figure3Config.presentation.column_label_font_size);
    labelHandles.nrf = local_figure_label(figure3Figure, ...
        figure3Config.presentation.label_positions.nrf, ...
        figure3Config.labels.nrf, 'figure3-label-nrf', 'center', ...
        figure3Config.presentation.column_label_font_size);

    drawnow;
    set(dataAxes(3), 'Position', figure3Config.presentation.axes_positions(3, :));
    set(dataAxes(4), 'Position', figure3Config.presentation.axes_positions(4, :));
    set(tfReferenceHandles.colorbar, 'Position', ...
        figure3Config.presentation.colourbar_positions(1, :));
    set(tfTrueHandles.colorbar, 'Position', ...
        figure3Config.presentation.colourbar_positions(2, :));

    figure3PanelData = struct();
    figure3PanelData.event_series = seriesByEvent;
    figure3PanelData.time_series_reference = tsReference;
    figure3PanelData.time_series_true = tsTrue;
    figure3PanelData.time_frequency_reference = tfReference;
    figure3PanelData.time_frequency_true = tfTrue;
    figure3PanelData.psd_reference = psdReference;
    figure3PanelData.psd_true = psdTrue;
    figure3PanelData.qc_separation = qcSeparation;
    figure3PanelData.nrf_separation = nrfSeparation;

    figure3PanelHandles = struct();
    figure3PanelHandles.data_axes = dataAxes;
    figure3PanelHandles.time_series_reference = tsReferenceHandles;
    figure3PanelHandles.time_series_true = tsTrueHandles;
    figure3PanelHandles.time_frequency_reference = tfReferenceHandles;
    figure3PanelHandles.time_frequency_true = tfTrueHandles;
    figure3PanelHandles.psd_reference = psdReferenceHandles;
    figure3PanelHandles.psd_true = psdTrueHandles;
    figure3PanelHandles.qc_separation = qcSeparationHandles;
    figure3PanelHandles.nrf_separation = nrfSeparationHandles;
    figure3PanelHandles.labels = labelHandles;

    expectedAxesTags = [ ...
        "figure3-ts-reference"; "figure3-ts-true"; ...
        "figure3-tf-reference"; "figure3-tf-true"; ...
        "figure3-psd-reference"; "figure3-psd-true"; ...
        "figure3-qc-separation"; "figure3-nrf-separation"];
    actualAxesTags = string(get(dataAxes, 'Tag'));
    if ~isequal(actualAxesTags(:), expectedAxesTags) || ...
            numel(unique(actualAxesTags)) ~= 8
        error('SimpleOxford:Step81:PanelInventoryMismatch', ...
            'The eight tagged data axes are incomplete or out of order.');
    end
    for axesIndex = 1:8
        if local_title_is_nonempty(dataAxes(axesIndex))
            error('SimpleOxford:Step81:UnexpectedPanelTitle', ...
                'Data axes %s unexpectedly has a title.', actualAxesTags(axesIndex));
        end
    end
    labelTags = string({labelHandles.part_a.Tag; labelHandles.reference.Tag; ...
        labelHandles.true.Tag; labelHandles.part_b.Tag; ...
        labelHandles.qc.Tag; labelHandles.nrf.Tag});
    expectedLabelTags = ["figure3-label-part-a"; "figure3-label-reference"; ...
        "figure3-label-true"; "figure3-label-part-b"; ...
        "figure3-label-qc"; "figure3-label-nrf"];
    if ~isequal(labelTags(:), expectedLabelTags) || numel(unique(labelTags)) ~= 6
        error('SimpleOxford:Step81:LabelInventoryMismatch', ...
            'The six tagged figure-level labels are incomplete or out of order.');
    end

    %% Validate a staged PDF before replacing the final output
    if isfile(resultsDir)
        error('SimpleOxford:Step81:ResultsPathIsFile', ...
            'The results path is a file rather than a directory: %s.', resultsDir);
    end
    if ~isfolder(resultsDir)
        [created, createMessage] = mkdir(resultsDir);
        if ~created
            error('SimpleOxford:Step81:CreateResultsFailed', ...
                'Could not create results directory %s: %s.', ...
                resultsDir, createMessage);
        end
        figure3ResultsDirCreated = true;
    end

    local_recover_owned_pdf(figure3FinalPdf, ...
        figure3PartialPdf, figure3RollbackPdf);
    exportgraphics(figure3Figure, figure3PartialPdf, 'ContentType', 'vector');
    local_validate_pdf(figure3PartialPdf);

    % Keep rendering independent of desktop/window-manager size, then reveal
    % the validated figure for the author's D-081 inspection before commit.
    set(figure3Figure, 'Visible', 'on');
    drawnow;

    qcInterval = qcSeparation.estimate.ConfidenceIntervals(1, :);
    nrfInterval = nrfSeparation.estimate.ConfidenceIntervals(1, :);
    fprintf('\nFigure 3 panel summary:\n');
    fprintf('  Part A internal reference: candidates=%d | excluded=%d | admitted=%d\n', ...
        seriesByEvent(1).n_candidates, seriesByEvent(1).n_excluded, ...
        seriesByEvent(1).n_admitted);
    fprintf('  Part A true event: candidates=%d | excluded=%d | admitted=%d\n', ...
        seriesByEvent(2).n_candidates, seriesByEvent(2).n_excluded, ...
        seriesByEvent(2).n_admitted);
    fprintf('  QC separation: pairs=%d | estimate=%.17g | 95%% BCa CI [%.17g, %.17g]\n', ...
        height(qcPairs), qcSeparation.estimate.Estimate(1), ...
        qcInterval(1), qcInterval(2));
    fprintf('  NRF separation: pairs=%d | estimate=%.17g | 95%% BCa CI [%.17g, %.17g]\n', ...
        height(nrfPairs), nrfSeparation.estimate.Estimate(1), ...
        nrfInterval(1), nrfInterval(2));
    fprintf('Completed Step 8.1 guardrail figure preparation; committing PDF: %s\n', ...
        figure3FinalPdf);

    %% Transactional promotion and finalisation
    figure3HadPriorFinal = isfile(figure3FinalPdf);
    if figure3HadPriorFinal
        [moved, moveMessage] = movefile( ...
            figure3FinalPdf, figure3RollbackPdf, 'f');
        if ~moved
            error('SimpleOxford:Step81:PreservePriorPdfFailed', ...
                'Could not preserve the prior final PDF: %s.', moveMessage);
        end
        figure3RollbackReady = true;
    end
    if figure3InternalFailpoint == "after-rollback"
        error('SimpleOxford:Step81:InjectedFailure', ...
            'Injected failure after preserving the prior final PDF.');
    end

    [moved, moveMessage] = movefile( ...
        figure3PartialPdf, figure3FinalPdf, 'f');
    if ~moved
        error('SimpleOxford:Step81:PromotePdfFailed', ...
            'Could not promote the validated PDF: %s.', moveMessage);
    end
    figure3PdfPromoted = true;
    if figure3InternalFailpoint == "after-promotion"
        error('SimpleOxford:Step81:InjectedFailure', ...
            'Injected failure after promoting the new final PDF.');
    end

    figure3LogStopAttempted = true;
    log_command_window('stop');
    figure3LogActive = false;
    if figure3InternalFailpoint == "after-log-stop"
        error('SimpleOxford:Step81:InjectedFailure', ...
            'Injected failure after stopping the Command Window log.');
    end
    if figure3RollbackReady
        local_delete_owned_file(figure3RollbackPdf);
        figure3RollbackReady = false;
    end
catch ME
    diagnostic = sprintf('Step 8.1 failed.\n%s', ...
        getReport(ME, 'extended', 'hyperlinks', 'off'));
    fprintf(2, '\n%s\n', diagnostic);

    cleanupIssues = local_cleanup_failed_transaction( ...
        figure3FinalPdf, figure3PartialPdf, figure3RollbackPdf, ...
        figure3HadPriorFinal, figure3RollbackReady, figure3PdfPromoted, ...
        figure3Figure, resultsDir, figure3ResultsDirCreated);
    if figure3LogActive
        if ~isempty(cleanupIssues)
            fprintf(2, 'Step 8.1 cleanup issue(s):\n  %s\n', ...
                strjoin(cleanupIssues, '\n  '));
        end
        if ~figure3LogStopAttempted
            try
                figure3LogStopAttempted = true;
                log_command_window('stop');
                figure3LogActive = false;
            catch stopError
                stopIssue = "Could not stop logger normally: " + ...
                    string(stopError.message);
                try
                    diary off;
                catch diaryError
                    stopIssue = stopIssue + ...
                        "; direct diary-off fallback also failed: " + ...
                        string(diaryError.message);
                end
                figure3LogActive = false;
                cleanupIssues(end+1, 1) = stopIssue; %#ok<SAGROW>
                local_append_log(figure3LogPath, ...
                    sprintf('Step 8.1 cleanup issue:\n  %s', stopIssue));
            end
        else
            stopIssue = "The single logger-stop attempt failed; direct " + ...
                "diary-off fallback was required.";
            try
                diary off;
            catch diaryError
                stopIssue = stopIssue + " Fallback also failed: " + ...
                    string(diaryError.message);
            end
            figure3LogActive = false;
            cleanupIssues(end+1, 1) = stopIssue; %#ok<SAGROW>
            logText = sprintf('%s\nStep 8.1 cleanup issue(s):\n  %s', ...
                diagnostic, strjoin(cleanupIssues, '\n  '));
            local_append_log(figure3LogPath, logText);
        end
    else
        logText = diagnostic;
        if ~isempty(cleanupIssues)
            logText = sprintf('%s\nStep 8.1 cleanup issue(s):\n  %s', ...
                logText, strjoin(cleanupIssues, '\n  '));
        end
        local_append_log(figure3LogPath, logText);
    end
    if ~isempty(cleanupIssues)
        cleanupException = MException( ...
            'SimpleOxford:Step81:CleanupIncomplete', ...
            'Failure cleanup reported: %s', strjoin(cleanupIssues, ' | '));
        ME = addCause(ME, cleanupException);
    end
    rethrow(ME);
end

