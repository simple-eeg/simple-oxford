function local_recover_owned_pdf(finalPath, partialPath, rollbackPath)
ownedPaths = {finalPath, partialPath, rollbackPath};
for pathIndex = 1:numel(ownedPaths)
    if isfolder(ownedPaths{pathIndex})
        error('SimpleOxford:Step81:OwnedPathIsDirectory', ...
            'An owned PDF path is unexpectedly a directory: %s.', ...
            ownedPaths{pathIndex});
    end
end
if isfile(rollbackPath)
    if isfile(finalPath)
        local_delete_owned_file(rollbackPath);
    else
        [moved, moveMessage] = movefile(rollbackPath, finalPath, 'f');
        if ~moved
            error('SimpleOxford:Step81:RollbackRecoveryFailed', ...
                'Could not restore an interrupted prior PDF: %s.', moveMessage);
        end
    end
end
local_delete_owned_file(partialPath);
end

function local_validate_pdf(pdfPath)
fileInfo = dir(pdfPath);
if numel(fileInfo) ~= 1 || fileInfo.isdir || fileInfo.bytes <= 100
    error('SimpleOxford:Step81:InvalidPdf', ...
        'The staged PDF is absent or too small to be valid: %s.', pdfPath);
end
[fid, openMessage] = fopen(pdfPath, 'rb');
if fid < 0
    error('SimpleOxford:Step81:InvalidPdf', ...
        'Could not open staged PDF %s: %s.', pdfPath, openMessage);
end
fileCleanup = onCleanup(@() fclose(fid));
header = fread(fid, 5, '*uint8');
if ~isequal(header(:), uint8([37; 80; 68; 70; 45]))
    error('SimpleOxford:Step81:InvalidPdf', ...
        'The staged output does not begin with the PDF header.');
end
clear fileCleanup;
end

function local_delete_owned_file(filePath)
if isfolder(filePath)
    error('SimpleOxford:Step81:RefuseDirectoryDelete', ...
        'Refusing to delete a directory at an owned file path: %s.', filePath);
end
if isfile(filePath)
    delete(filePath);
end
end

function issues = local_cleanup_failed_transaction(finalPath, partialPath, ...
        rollbackPath, hadPriorFinal, rollbackReady, pdfPromoted, ...
        candidateFigure, resultsDir, resultsDirCreated)
issues = strings(0, 1);
rollbackRestoreFailed = false;
try
    if (rollbackReady || hadPriorFinal) && isfile(rollbackPath)
        local_delete_owned_file(finalPath);
        [restored, restoreMessage] = movefile(rollbackPath, finalPath, 'f');
        if ~restored
            error('Could not restore the prior final PDF: %s', restoreMessage);
        end
    elseif pdfPromoted && ~hadPriorFinal
        local_delete_owned_file(finalPath);
        if isfile(rollbackPath)
            [restored, restoreMessage] = movefile( ...
                rollbackPath, finalPath, 'f');
            if ~restored
                error(['Could not restore a pre-existing rollback PDF ', ...
                    'after removing the failed promoted PDF: %s'], ...
                    restoreMessage);
            end
        end
    elseif ~rollbackReady && ~hadPriorFinal && isfile(rollbackPath)
        if isfile(finalPath)
            local_delete_owned_file(rollbackPath);
        else
            [restored, restoreMessage] = movefile( ...
                rollbackPath, finalPath, 'f');
            if ~restored
                error(['Could not recover the pre-existing rollback PDF ', ...
                    'after an early failure: %s'], restoreMessage);
            end
        end
    end
catch cleanupError
    rollbackRestoreFailed = isfile(rollbackPath);
    issues(end+1, 1) = "PDF rollback failed: " + string(cleanupError.message); %#ok<AGROW>
end
try
    local_delete_owned_file(partialPath);
catch cleanupError
    issues(end+1, 1) = "Partial-PDF cleanup failed: " + string(cleanupError.message); %#ok<AGROW>
end
try
    if isfile(rollbackPath)
        if rollbackRestoreFailed
            error(['Rollback PDF retained because deleting it could destroy ', ...
                'the only recoverable prior output: %s'], rollbackPath);
        end
        local_delete_owned_file(rollbackPath);
    end
catch cleanupError
    issues(end+1, 1) = "Rollback-PDF cleanup failed: " + string(cleanupError.message); %#ok<AGROW>
end
try
    if isgraphics(candidateFigure)
        close(candidateFigure);
    end
catch cleanupError
    issues(end+1, 1) = "Candidate-figure cleanup failed: " + string(cleanupError.message); %#ok<AGROW>
end
try
    if resultsDirCreated && isfolder(resultsDir)
        entries = dir(resultsDir);
        entries = entries(~ismember({entries.name}, {'.','..'}));
        if isempty(entries)
            [removed, removeMessage] = rmdir(resultsDir);
            if ~removed
                error('Could not remove empty created results directory: %s', ...
                    removeMessage);
            end
        end
    end
catch cleanupError
    issues(end+1, 1) = "Results-directory cleanup failed: " + string(cleanupError.message); %#ok<AGROW>
end
end

function local_append_log(logPath, textValue)
[fid, openMessage] = fopen(logPath, 'a');
if fid < 0
    fprintf(2, 'Could not append failure diagnostic to %s: %s\n', ...
        logPath, openMessage);
    return;
end
fileCleanup = onCleanup(@() fclose(fid));
fprintf(fid, '\n%s\n', textValue);
clear fileCleanup;
end
