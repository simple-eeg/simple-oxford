function tf = value_contains_token(value, token)
tf = false;
if ischar(value) || isstring(value) || iscategorical(value)
    tf = any(contains(lower(string(value)), lower(string(token))), 'all');
elseif iscell(value)
    for valueIndex = 1:numel(value)
        if value_contains_token(value{valueIndex}, token)
            tf = true;
            return;
        end
    end
elseif istable(value)
    for variableIndex = 1:width(value)
        variableName = value.Properties.VariableNames{variableIndex};
        if value_contains_token(value.(variableName), token)
            tf = true;
            return;
        end
    end
elseif isstruct(value)
    fields = fieldnames(value);
    for elementIndex = 1:numel(value)
        for fieldIndex = 1:numel(fields)
            if value_contains_token(value(elementIndex).(fields{fieldIndex}), token)
                tf = true;
                return;
            end
        end
    end
end
end

function snapshot = snapshot_regular_files(root)
items = dir(fullfile(root, '**', '*'));
items = items(~[items.isdir]);
paths = strings(numel(items), 1);
hashes = strings(numel(items), 1);
for i = 1:numel(items)
    paths(i) = string(erase(fullfile(items(i).folder, items(i).name), ...
        [root filesep]));
    hashes(i) = local_file_sha256(fullfile(items(i).folder, items(i).name));
end
[paths, order] = sort(paths);
hashes = hashes(order);
snapshot = table(paths, hashes);
end

function digest = local_file_sha256(path)
fid = fopen(path, 'rb');
assert(fid >= 0, 'Could not read fixture file: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = fread(fid, Inf, '*uint8');
md = java.security.MessageDigest.getInstance('SHA-256');
if ~isempty(bytes)
    md.update(bytes);
end
digest = lower(string(char(dec2hex(typecast(md.digest(), 'uint8'), 2)')));
digest = join(digest, "");
end

