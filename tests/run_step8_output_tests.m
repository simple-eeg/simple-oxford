function T = read_text_table(filePath)
options = detectImportOptions(filePath, ...
    'PreserveVariableNames', true, 'TextType', 'string');
options.DataLines = [2 Inf];
options = setvartype(options, options.VariableNames, 'string');
T = readtable(filePath, options);
for i = 1:width(T)
    values = string(T.(i));
    values(ismissing(values)) = "";
    T.(i) = values;
end
end

function names = sorted_file_names(folder, pattern)
listing = dir(fullfile(folder, pattern));
listing = listing(~[listing.isdir]);
names = sort({listing.name});
end

