function result = run_step8_output_tests(repoRoot)
%RUN_STEP8_OUTPUT_TESTS Exercise the public Step 8 manuscript outputs.

arguments
    repoRoot (1,:) char
end

sampleDetails = run_sample_details_positive(repoRoot);
incomplete = run_sample_details_failure(repoRoot, "incomplete");
category = run_sample_details_failure(repoRoot, "category");
nrfDetails = run_nrf_details_positive(repoRoot);
nrfMissingTemplate = run_nrf_details_missing_template(repoRoot);

result = struct( ...
    'sample_details', sampleDetails, ...
    'incomplete_rejected', incomplete, ...
    'category_rejected', category, ...
    'nrf_details', nrfDetails, ...
    'nrf_missing_template_rejected', nrfMissingTemplate, ...
    'total', sampleDetails + incomplete + category + nrfDetails + ...
        nrfMissingTemplate);
fprintf(['STEP 8 OUTPUT TESTS PASSED: sample_details=%d, ' ...
    ['incomplete_rejected=%d, category_rejected=%d, ' ...
    'nrf_details=%d, nrf_missing_template_rejected=%d\n']], ...
    result.sample_details, result.incomplete_rejected, ...
    result.category_rejected, result.nrf_details, ...
    result.nrf_missing_template_rejected);
end

