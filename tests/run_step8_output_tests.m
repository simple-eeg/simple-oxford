end

function assert_failure_log_only(root, before, scriptName)
logPath = assert_exact_log_inventory(root, scriptName);
after = snapshot_regular_files(root);
relativeLogPath = string(erase(logPath, [root filesep]));
afterWithoutLog = after(after.paths ~= relativeLogPath, :);
assert(isequal(before, afterWithoutLog), ...
    'A rejected Step 8 fixture changed something other than its log.');
end

function snapshot = snapshot_regular_files(root)
items = dir(fullfile(root, '**', '*'));
items = items(~[items.isdir]);
paths = strings(numel(items), 1);
hashes = strings(numel(items), 1);
for i = 1:numel(items)
    paths(i) = string(erase(fullfile(items(i).folder, items(i).name), ...
        [root filesep]));
    hashes(i) = local_file_sha256(fullfile(items(i).folder, items(i).name));
end
[paths, order] = sort(paths);
hashes = hashes(order);
snapshot = table(paths, hashes);
end

function digest = local_file_sha256(path)
fid = fopen(path, 'rb');
assert(fid >= 0, 'Could not read fixture file: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = fread(fid, Inf, '*uint8');
md = java.security.MessageDigest.getInstance('SHA-256');
if ~isempty(bytes)
    md.update(bytes);
end
digest = lower(string(char(dec2hex(typecast(md.digest(), 'uint8'), 2)')));
digest = join(digest, "");
end

function bytes = read_binary(filePath)
fid = fopen(filePath, 'rb');
assert(fid >= 0, 'Could not read fixture output: %s', filePath);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = fread(fid, Inf, '*uint8');
end

function assert_excel_utf8_csv(filePath)
bytes = read_binary(filePath);
utf8Bom = uint8([239; 187; 191]);
assert(numel(bytes) >= 3 && isequal(bytes(1:3), utf8Bom), ...
    'CSV lacks the UTF-8 BOM required for reliable direct opening in Excel.');
end

function copy_script_with_fixture_root(sourcePath, destinationPath, root)
assert(isfile(sourcePath), 'Public script is missing: %s', sourcePath);
source = fileread(sourcePath);
pattern = 'baseDir\s*=\s*''[^'']+'';';
matches = regexp(source, pattern, 'match');
assert(numel(matches) == 1, ...
    'Expected one configurable baseDir assignment in %s.', sourcePath);
escapedRoot = strrep(root, '''', '''''');
replacement = sprintf('baseDir = ''%s'';', escapedRoot);
source = regexprep(source, pattern, replacement, 'once');
write_text(destinationPath, source);
end

function bind_fixture_logger(repoRoot, scriptsRoot)
sourcePath = fullfile(repoRoot, 'scripts', 'log_command_window.m');
destinationPath = fullfile(scriptsRoot, 'log_command_window.m');
assert(isfile(sourcePath), 'Public logging helper is missing: %s', sourcePath);
copyfile(sourcePath, destinationPath);
addpath(scriptsRoot, '-begin');
clear log_command_window
rehash path;
assert(strcmp(which('log_command_window'), destinationPath), ...
    'The Step 8 fixture did not bind its temporary logger.');
end

function run_fixture_script(scriptPath)
scriptFolder = fileparts(scriptPath);
cd(scriptFolder);
evalin('base', 'clear;');
diaryCleanup = onCleanup(@() diary('off')); %#ok<NASGU>
command = sprintf('run(''%s'');', strrep(scriptPath, '''', ''''''));
evalin('base', command);
end

function write_text(filePath, value)
fid = fopen(filePath, 'wt');
assert(fid >= 0, 'Could not create fixture script: %s', filePath);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
count = fwrite(fid, value, 'char');
assert(count == numel(value));
end

function cleanup_fixture(root, originalFolder, originalPath)
diary off;
if isfolder(originalFolder)
    cd(originalFolder);
end
evalin('base', 'clear;');
close all force;
path(originalPath);
clear NRFUtils log_command_window
if isfolder(root)
    rmdir(root, 's');
end
rehash path;
end
