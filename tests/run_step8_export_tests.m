function result = run_step8_export_tests(repoRoot)
%RUN_STEP8_EXPORT_TESTS Exercise the public Step 8 CSV export scripts.

arguments
    repoRoot (1,:) char
end

originalFolder = pwd;
originalPath = path;
temporaryRoot = tempname;
mkdir(temporaryRoot);
cleanup = onCleanup(@() cleanup_fixture( ...
    temporaryRoot, originalFolder, originalPath)); %#ok<NASGU>

scriptsRoot = fullfile(temporaryRoot, 'scripts');
screeningRoot = fullfile(temporaryRoot, 'data', 'summary', 'screening');
dataListsRoot = fullfile(temporaryRoot, 'data_lists');
mkdir(scriptsRoot);
mkdir(screeningRoot);
mkdir(dataListsRoot);

copyfile(fullfile(repoRoot, 'scripts', 'log_command_window.m'), ...
    fullfile(scriptsRoot, 'log_command_window.m'));
addpath(scriptsRoot, '-begin');
clear log_command_window
rehash path;
assert(strcmp(which('log_command_window'), ...
    fullfile(scriptsRoot, 'log_command_window.m')), ...
    'The Step 8 fixture did not bind its temporary logger.');
copy_script_with_fixture_root( ...
    fullfile(repoRoot, 'scripts', 'step_8_jasp_1_data_prep_eeg_qc.m'), ...
    fullfile(scriptsRoot, 'step_8_jasp_1_data_prep_eeg_qc.m'), ...
    temporaryRoot);
copy_script_with_fixture_root( ...
    fullfile(repoRoot, 'scripts', 'step_8_jasp_2_data_prep_eeg_nrf.m'), ...
    fullfile(scriptsRoot, 'step_8_jasp_2_data_prep_eeg_nrf.m'), ...
    temporaryRoot);
for stepName = [ ...
        "step_8_jasp_3_data_prep_eeg_combine.m", ...
        "step_8_jasp_4_data_prep_other.m", ...
        "step_8_jasp_5_data_prep_combine_all.m", ...
        "step_8_jasp_6_add_bvt_cols.m"]
    copy_script_with_fixture_root( ...
        fullfile(repoRoot, 'scripts', char(stepName)), ...
        fullfile(scriptsRoot, char(stepName)), ...
        temporaryRoot);
end

[inputTable, metrics] = qc_fixture();
writetable(inputTable, fullfile(screeningRoot, ...
    'pooled_screened_eeg_qc_features.csv'));

run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_1_data_prep_eeg_qc.m'));

outputPath = fullfile(temporaryRoot, 'data', 'results', ...
    'jasp_data_eeg_qc.csv');
assert(isfile(outputPath), 'Step 8.1 did not create its public CSV output.');
outputOptions = detectImportOptions(outputPath, ...
    'TextType', 'string', 'PreserveVariableNames', true);
outputOptions = setvartype(outputOptions, 'subjectID', 'string');
outputTable = readtable(outputPath, outputOptions);

expectedNames = [{'subjectID'}, ...
    strcat('HL_BL_', cellstr(metrics)), ...
    strcat('HL_ER_', cellstr(metrics))];
assert(isequal(outputTable.Properties.VariableNames, expectedNames), ...
    'Step 8.1 did not expose the pain-only QC schema.');
assert(isequal(string(outputTable.subjectID), ...
    ["Ox60001"; "Ox60002"; "Ox60003"]));

for metricIndex = 1:numel(metrics)
    metric = char(metrics(metricIndex));
    expectedBaseline = [400 + metricIndex; 600 + metricIndex; NaN];
    expectedEvent = [200 + metricIndex; NaN; 500 + metricIndex];
    assert(isequaln(outputTable.(['HL_BL_' metric]), expectedBaseline));
    assert(isequaln(outputTable.(['HL_ER_' metric]), expectedEvent));
end

[nrfInput, nrfNames] = nrf_fixture();
writetable(nrfInput, fullfile(screeningRoot, ...
    'pooled_screened_eeg_nrf_features.csv'));
run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_2_data_prep_eeg_nrf.m'));

nrfOutputPath = fullfile(temporaryRoot, 'data', 'results', ...
    'jasp_data_eeg_nrf.csv');
assert(isfile(nrfOutputPath), 'Step 8.2 did not create its public CSV output.');
nrfOptions = detectImportOptions(nrfOutputPath, ...
    'TextType', 'string', 'PreserveVariableNames', true);
nrfOptions = setvartype(nrfOptions, 'subjectID', 'string');
nrfOutput = readtable(nrfOutputPath, nrfOptions);
expectedNrfNames = { ...
    'subjectID', ...
    'HL_BL_eNRF_mag', ...
    'HL_BL_nNRF_mag', ...
    'HL_ER_eNRF_mag', ...
    'HL_ER_nNRF_mag'};
assert(isequal(nrfOutput.Properties.VariableNames, expectedNrfNames), ...
    'Step 8.2 did not expose the pain-only NRF schema.');
assert(isequal(string(nrfOutput.subjectID), ...
    ["Ox60001"; "Ox60002"; "Ox60003"]));
assert(isequaln(nrfOutput.HL_BL_eNRF_mag, [111; 211; NaN]));
assert(isequaln(nrfOutput.HL_BL_nNRF_mag, [112; 212; NaN]));
assert(isequaln(nrfOutput.HL_ER_eNRF_mag, [121; NaN; 321]));
assert(isequaln(nrfOutput.HL_ER_nNRF_mag, [122; NaN; 322]));
assert(isequal(unique(string(nrfInput.NRFName)), sort(nrfNames)'));

% Deliberately disturb the physical NRF row order so Step 8.3 must align
% by subjectID rather than concatenate rows by their current order.
writetable(nrfOutput([3 1 2], :), nrfOutputPath);

finalPath = fullfile(temporaryRoot, 'data', 'results', ...
    'jasp_data_all.csv');
write_metadata_fixtures(dataListsRoot);

run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_3_data_prep_eeg_combine.m'));
eegPath = fullfile(temporaryRoot, 'data', 'results', ...
    'jasp_data_eeg.csv');
eegTable = read_csv(eegPath);
nrfVars = setdiff(nrfOutput.Properties.VariableNames, {'subjectID'}, 'stable');
expectedEeg = [outputTable, nrfOutput(:, nrfVars)];
assert(isequaln(eegTable, expectedEeg));

run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_4_data_prep_other.m'));
otherPath = fullfile(temporaryRoot, 'data', 'results', ...
    'jasp_data_other.csv');
otherTable = read_csv(otherPath);
expectedOther = table( ...
    ["Ox50000"; "Ox60001"; "Ox60002"; "Ox60003"], ...
    ["Control"; "Intervention"; "Control"; "Intervention"], ...
    ["Awake"; "Asleep"; "Awake"; "Asleep"], ...
    'VariableNames', {'subjectID', 'trial_arm', 'HL_sleep_state'});
assert(isequaln(otherTable, expectedOther));

run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_5_data_prep_combine_all.m'));
assert(isfile(finalPath), ...
    'The Step 8.5 provisional combined CSV was not created.');
provisional = read_csv(finalPath);
expectedProvisional = [expectedEeg, expectedOther(2:4, 2:3)];
assert(isequaln(provisional, expectedProvisional));

run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_6_add_bvt_cols.m'));
complete = read_csv(finalPath);
ownedColumns = { ...
    'HL_ER_nNRF_mag_Screening', ...
    'HL_ER_nNRF_mag_pub', ...
    'HL_ER_nNRF_mag_pub_Screening'};
expectedFinalNames = [provisional.Properties.VariableNames, ownedColumns];
assert(isequal(size(complete), [3 28]));
assert(isequal(complete.Properties.VariableNames, expectedFinalNames));
assert(isequaln(complete(:, provisional.Properties.VariableNames), ...
    provisional));
assert(isequal(string(complete.HL_ER_nNRF_mag_Screening), ...
    ["Included"; "Excluded"; "Included"]));
assert(isequaln(complete.HL_ER_nNRF_mag_pub, [122; NaN; NaN]));
assert(isequal(string(complete.HL_ER_nNRF_mag_pub_Screening), ...
    ["Included"; "Excluded"; "Excluded"]));
assert(~any(string(complete.subjectID) == "Ox50000"));

resultsRoot = fullfile(temporaryRoot, 'data', 'results');
csvNames = sorted_file_names(resultsRoot, '*.csv');
expectedCsvNames = { ...
    'jasp_data_all.csv', ...
    'jasp_data_eeg.csv', ...
    'jasp_data_eeg_nrf.csv', ...
    'jasp_data_eeg_qc.csv', ...
    'jasp_data_other.csv'};
assert(isequal(csvNames, expectedCsvNames));
assert(isequal(sorted_file_names(resultsRoot, '*'), expectedCsvNames), ...
    'Step 8 created an unexpected non-CSV artifact.');
assert(~isfolder(fullfile(temporaryRoot, 'data', 'jasp')), ...
    'Step 8 created the retired data/jasp directory.');

run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_6_add_bvt_cols.m'));
assert(isequaln(read_csv(finalPath), complete), ...
    'Step 8.6 was not semantically idempotent.');

run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_5_data_prep_combine_all.m'));
rebuiltProvisional = read_csv(finalPath);
assert(isequaln(rebuiltProvisional, provisional));
assert(isempty(intersect(ownedColumns, ...
    rebuiltProvisional.Properties.VariableNames)));
run_fixture_script(fullfile(scriptsRoot, ...
    'step_8_jasp_6_add_bvt_cols.m'));
assert(isequaln(read_csv(finalPath), complete), ...
    'Steps 8.5 and 8.6 did not reconstruct the exact final table.');

expectedLogs = { ...
    'step_8_jasp_1_data_prep_eeg_qc.log', ...
    'step_8_jasp_2_data_prep_eeg_nrf.log', ...
    'step_8_jasp_3_data_prep_eeg_combine.log', ...
    'step_8_jasp_4_data_prep_other.log', ...
    'step_8_jasp_5_data_prep_combine_all.log', ...
    'step_8_jasp_6_add_bvt_cols.log'};
logRoot = fullfile(temporaryRoot, 'data', 'logs');
assert(isequal(sorted_file_names(logRoot, '*'), expectedLogs));
expectedMessages = { ...
    'Wrote Step 8.1 intermediate:', ...
    'Wrote Step 8.2 intermediate:', ...
    'Wrote Step 8.3 intermediate:', ...
    'Wrote Step 8.4 intermediate:', ...
    'Wrote Step 8.5 provisional table:', ...
    'Finalised Step 8 JASP table:'};
for logIndex = 1:numel(expectedLogs)
    logText = fileread(fullfile(logRoot, expectedLogs{logIndex}));
    assert(contains(logText, expectedMessages{logIndex}), ...
        'Step 8 success log lacks its completion message: %s', ...
        expectedLogs{logIndex});
end

result = struct('qc', 1, 'nrf', 1, 'complete_chain', 1, ...
    'repeatable_finalization', 1, 'total', 4);
fprintf(['STEP 8 EXPORT TESTS PASSED: qc=%d, nrf=%d, ' ...
    'complete_chain=%d, repeatable_finalization=%d\n'], ...
    result.qc, result.nrf, result.complete_chain, ...
    result.repeatable_finalization);
end

