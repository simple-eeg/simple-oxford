    "lance_prestim"; "lance"; "lance_prestim"];
Exclude = [1; 0; 1; 0; 0; 0];
T = table(subjectID, sessionID, runID, epoch_index, channel, ...
    eventtype, Exclude);
metrics = [ ...
    "maxAbsEpoch", ...
    "sdEpoch", ...
    "invSdEpoch", ...
    "MeanAbsDiffNorm", ...
    "MaxAbsDiffNorm", ...
    "RobustSlopeNorm", ...
    "AutoCorrLag1Pos", ...
    "AutoCorrLag1Neg", ...
    "KatzFDNorm" ...
    ];
for metricIndex = 1:numel(metrics)
    T.(char(metrics(metricIndex))) = (1:6)' * 100 + metricIndex;
end
end

function [T, nrfNames] = nrf_fixture()
subjectID = strings(12, 1);
sessionID = repmat("01", 12, 1);
runID = repmat("01", 12, 1);
eventtype = strings(12, 1);
channel = repmat("CZ", 12, 1);
NRFName = strings(12, 1);
fglsCoef = nan(12, 1);
Exclude = zeros(12, 1);
nrfNames = ["early_NRF_500Hz", "noxious_NRF_500Hz"];
row = 0;
for subjectIndex = 1:3
    for eventIndex = 1:2
        for nrfIndex = 1:2
            row = row + 1;
            subjectID(row) = sprintf('Ox600%02d', subjectIndex);
            if eventIndex == 1
                eventtype(row) = "lance_prestim";
            else
                eventtype(row) = "lance";
            end
            NRFName(row) = nrfNames(nrfIndex);
            fglsCoef(row) = subjectIndex * 100 + eventIndex * 10 + nrfIndex;
            Exclude(row) = (subjectIndex == 2 && eventIndex == 2) || ...
                (subjectIndex == 3 && eventIndex == 1);
        end
    end
end
T = table(subjectID, sessionID, runID, eventtype, channel, NRFName, ...
    fglsCoef, Exclude);
end

