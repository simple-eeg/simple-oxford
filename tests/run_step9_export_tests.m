function passed = run_mapped_identity_chain(repoRoot)
originalFolder = pwd;
originalPath = path;
originalRoot = tempname;
mappedRoot = tempname;
mkdir(originalRoot);
mkdir(mappedRoot);
cleanup = onCleanup(@() cleanup_identity_pair( ...
    originalRoot, mappedRoot, originalFolder, originalPath)); %#ok<NASGU>

originalSubjects = "Ox6" + compose('%04d', (1:104)');
canonicalSubjects = compose('%03d', (1:104)');

setup_complete_identity_fixture(repoRoot, originalRoot, "original", ...
    originalSubjects, canonicalSubjects);
setup_complete_identity_fixture(repoRoot, mappedRoot, "mapped", ...
    originalSubjects, canonicalSubjects);

original = run_complete_identity_route(originalRoot, "original");
mapped = run_complete_identity_route(mappedRoot, "mapped");

assert(height(original.other) == 114, ...
    'Original Step 9.4 did not retain the ten metadata-only participants.');
assert(height(mapped.other) == 104, ...
    'Mapped Step 9.4 did not use the admitted registry cohort.');
[allAdmittedFound, originalOtherRows] = ismember( ...
    originalSubjects, string(original.other.subjectID));
assert(all(allAdmittedFound));
originalOtherAdmitted = original.other(originalOtherRows, :);

assert_same_science(original.qc, mapped.qc, 'Step 9.1');
assert_same_science(original.nrf, mapped.nrf, 'Step 9.2');
assert_same_science(original.eeg, mapped.eeg, 'Step 9.3');
assert_same_science(originalOtherAdmitted, mapped.other, 'Step 9.4');
assert_same_science(original.provisional, mapped.provisional, 'Step 9.5');
assert_same_science(original.final, mapped.final, 'Step 9.6');

assert(isequal(string(mapped.final.subjectID), canonicalSubjects));
expectedPublicationRows = ismember(canonicalSubjects, ["001", "010", "100"]);
expectedPublicationScreening = repmat("Excluded", 104, 1);
expectedPublicationScreening(expectedPublicationRows) = "Included";
assert(isequal(string(mapped.final.HL_ER_nNRF_mag_pub_Screening), ...
    expectedPublicationScreening));
assert(isequaln(mapped.final.HL_ER_nNRF_mag_pub(expectedPublicationRows), ...
    [104; 1004; 10004]));
expectedCurrentScreening = repmat("Included", 104, 1);
expectedCurrentScreening(104) = "Excluded";
assert(isequal(string(mapped.final.HL_ER_nNRF_mag_Screening), ...
    expectedCurrentScreening));
assert(isnan(mapped.final.HL_ER_nNRF_mag(104)), ...
    'The matched synthetic NRF exclusion did not remain missing.');

mappedResultsRoot = fullfile(mappedRoot, 'data', 'results');
mappedLogRoot = fullfile(mappedRoot, 'data', 'logs');
privacyText = "";
for outputName = [ ...
        "jasp_data_eeg_qc.csv", ...
        "jasp_data_eeg_nrf.csv", ...
        "jasp_data_eeg.csv", ...
        "jasp_data_other.csv", ...
        "jasp_data_all.csv"]
    privacyText = privacyText + newline + string(fileread( ...
        fullfile(mappedResultsRoot, char(outputName))));
end
for logName = [ ...
        "step_9_jasp_1_data_prep_eeg_qc.log", ...
        "step_9_jasp_2_data_prep_eeg_nrf.log", ...
        "step_9_jasp_3_data_prep_eeg_combine.log", ...
        "step_9_jasp_4_data_prep_other.log", ...
        "step_9_jasp_5_data_prep_combine_all.log", ...
        "step_9_jasp_6_add_bvt_cols.log"]
    privacyText = privacyText + newline + string(fileread( ...
        fullfile(mappedLogRoot, char(logName))));
end
privacyText = lower(privacyText);
for privateToken = ["ox6", "privatepart8888"]
    assert(~contains(privacyText, privateToken), ...
        'Mapped Step 9 output or log exposed private source identity text.');
end
assert(contains(string(fileread(fullfile(mappedLogRoot, ...
    'step_9_jasp_4_data_prep_other.log'))), ...
    '10 source-only participant(s) omitted'));

for privateVariable = ["identity", "participantMap", "X", ...
        "sourceSubjectID", "publicationSourceID", ...
        "publicationSourceIDAll"]
    assert(evalin('base', sprintf("exist('%s', 'var') == 0", ...
        privateVariable)), ...
        'Mapped Step 9 retained private source identity state: %s', ...
        privateVariable);
end

% A successful mapped Step 9.6 rerun must be byte-stable and retain every
% lexical replacement ID, including the required boundary examples.
finalPath = fullfile(mappedResultsRoot, 'jasp_data_all.csv');
finalBeforeRerun = fileread(finalPath);
run_fixture_script(fullfile(mappedRoot, 'scripts', ...
    'step_9_jasp_6_add_bvt_cols.m'));
assert(strcmp(fileread(finalPath), finalBeforeRerun), ...
    'Mapped Step 9.6 was not byte-stable on a successful rerun.');
assert_raw_subject_ids(finalPath, ["001", "002", "010", "100"]);

% A stale original namespace in mapped Step 9.5 must fail before replacing
% the previously accepted complete output.
otherPath = fullfile(mappedResultsRoot, 'jasp_data_other.csv');
staleOther = mapped.other;
staleOther.subjectID(1) = originalSubjects(1);
writetable(staleOther, otherPath);
finalBeforeFailure = fileread(finalPath);
try
    run_fixture_script(fullfile(mappedRoot, 'scripts', ...
        'step_9_jasp_5_data_prep_combine_all.m'));
    error('TEST:ExpectedFailure', ...
        'Mapped Step 9.5 unexpectedly accepted a stale original namespace.');
catch ME
    diary off;
    if ME.identifier == "TEST:ExpectedFailure"
        rethrow(ME);
    end
    assert(ME.identifier == ...
        "SimpleOxford:JaspCombineAll:MetadataRegistryMismatch");
end
assert(strcmp(fileread(finalPath), finalBeforeFailure), ...
    'Rejected mapped Step 9.5 replaced the accepted final CSV.');
failureLog = string(fileread(fullfile(mappedLogRoot, ...
    'step_9_jasp_5_data_prep_combine_all.log')));
assert(~contains(failureLog, originalSubjects(1)), ...
    'Mapped Step 9.5 failure log exposed an original participant ID.');
writetable(mapped.other, otherPath);

% A publication source participant without a registry mapping must also fail
% before replacing the completed CSV and must not enter the failure log.
unmappedProject = "OX6";
unmappedParticipant = "9998";
unmappedPublication = table(unmappedProject, unmappedParticipant, ...
    'VariableNames', { ...
        'RECD - Research project', ...
        'RECD - Participant number'});
writetable(unmappedPublication, fullfile(mappedRoot, 'data_lists', ...
    'medscinet_export_petal_pub.xlsx'));
finalBeforeFailure = fileread(finalPath);
try
    run_fixture_script(fullfile(mappedRoot, 'scripts', ...
        'step_9_jasp_6_add_bvt_cols.m'));
    error('TEST:ExpectedFailure', ...
        'Mapped Step 9.6 unexpectedly accepted an unmapped publication ID.');
catch ME
    diary off;
    if ME.identifier == "TEST:ExpectedFailure"
        rethrow(ME);
    end
    assert(ME.identifier == ...
        "SimpleOxford:JaspFinalise:MissingPublicationMapping");
end
assert(strcmp(fileread(finalPath), finalBeforeFailure), ...
    'Rejected mapped Step 9.6 replaced the completed final CSV.');
failureLog = string(fileread(fullfile(mappedLogRoot, ...
    'step_9_jasp_6_add_bvt_cols.log')));
assert(~contains(failureLog, "Ox69998") && ...
    ~contains(failureLog, "9998"), ...
    'Mapped Step 9.6 failure log exposed the unmapped source identifier.');

% An admitted-row Step 9.4 recoding failure must preserve its prior output,
% redact the planted source ID, and leave no candidate CSV behind.
metadataPath = fullfile(mappedRoot, 'data_lists', ...
    'medscinet_export_petal.xlsx');
metadataOptions = detectImportOptions(metadataPath, ...
    'PreserveVariableNames', true);
metadataTextColumns = intersect({ ...
    'RECD - Research project', ...
    'RECD - Participant number', ...
    'TESTOD - Relevant interventions during test occasion', ...
    ['Stimulus/Clinical Procedure 2: PIPP-R 2022 1: PIPPR - ' ...
     'Behavioural State']}, metadataOptions.VariableNames, 'stable');
metadataOptions = setvartype(metadataOptions, metadataTextColumns, 'string');
acceptedMetadata = readtable(metadataPath, metadataOptions);
acceptedOtherText = fileread(otherPath);

% Mapped Step 9.4 must require exactly one source row for each admitted
% original participant while ignoring malformed source-only rows.
missingMetadata = acceptedMetadata;
missingParticipants = string(missingMetadata.( ...
    'RECD - Participant number'));
missingParticipants(1) = "PRIVATEZERO7777";
missingMetadata.('RECD - Participant number') = missingParticipants;
writetable(missingMetadata, metadataPath);
assert_mapped_step94_identity_failure(mappedRoot, otherPath, ...
    acceptedOtherText, "SimpleOxford:JaspOther:MissingSourceMatch", ...
    ["ox60001", "privatezero7777"]);

duplicateMetadata = acceptedMetadata;
duplicateProjects = string(duplicateMetadata.( ...
    'RECD - Research project'));
duplicateParticipants = string(duplicateMetadata.( ...
    'RECD - Participant number'));
duplicateProjects(105) = "OX6";
duplicateParticipants(105) = "0001";
duplicateMetadata.('RECD - Research project') = duplicateProjects;
duplicateMetadata.('RECD - Participant number') = duplicateParticipants;
writetable(duplicateMetadata, metadataPath);
assert_mapped_step94_identity_failure(mappedRoot, otherPath, ...
    acceptedOtherText, ...
    "SimpleOxford:JaspOther:DuplicateAdmittedSourceID", "ox60001");

rejectedMetadata = acceptedMetadata;
rejectedArm = rejectedMetadata.( ...
    'TESTOD - Relevant interventions during test occasion');
rejectedArm(1) = originalSubjects(1);
rejectedMetadata.( ...
    'TESTOD - Relevant interventions during test occasion') = rejectedArm;
writetable(rejectedMetadata, metadataPath);
otherBeforeFailure = fileread(otherPath);
try
    run_fixture_script(fullfile(mappedRoot, 'scripts', ...
        'step_9_jasp_4_data_prep_other.m'));
    error('TEST:ExpectedFailure', ...
        'Mapped Step 9.4 unexpectedly accepted a private invalid category.');
catch ME
    diary off;
    if ME.identifier == "TEST:ExpectedFailure"
        rethrow(ME);
    end
    assert(ME.identifier == "SimpleOxford:JaspOther:UnexpectedTrialArm");
end
assert(strcmp(fileread(otherPath), otherBeforeFailure), ...
    'Rejected mapped Step 9.4 replaced its accepted CSV.');
failureLog = string(fileread(fullfile(mappedLogRoot, ...
    'step_9_jasp_4_data_prep_other.log')));
assert(~contains(failureLog, originalSubjects(1)), ...
    'Mapped Step 9.4 failure log exposed an original participant ID.');

assert(isequal(sorted_file_names(mappedResultsRoot, '*.csv'), { ...
    'jasp_data_all.csv', ...
    'jasp_data_eeg.csv', ...
    'jasp_data_eeg_nrf.csv', ...
    'jasp_data_eeg_qc.csv', ...
    'jasp_data_other.csv'}), ...
    'Mapped Step 9 left an unexpected candidate or result file.');

% Conversion failures in the shared MedSciNet-ID helper must not relay
% MATLAB's implementation-defined source-value diagnostics into a diary.
plantedSourceToken = "Ox" + "69876";
try
    construct_medscinet_subject_ids( ...
        struct('private_value', plantedSourceToken), "0001");
    error('TEST:ExpectedFailure', ...
        'The MedSciNet-ID helper unexpectedly accepted an unsupported value.');
catch ME
    if ME.identifier == "TEST:ExpectedFailure"
        rethrow(ME);
    end
    assert(ME.identifier == "SimpleOxford:MedSciNetSubjectID:InvalidInput");
    assert(~contains(string(ME.message), plantedSourceToken), ...
        'MedSciNet-ID conversion diagnostics exposed a source identifier.');
end
passed = 1;
end

function assert_mapped_step94_identity_failure( ...
        root, outputPath, acceptedOutputText, expectedIdentifier, privateTokens)
try
    run_fixture_script(fullfile(root, 'scripts', ...
        'step_9_jasp_4_data_prep_other.m'));
    error('TEST:ExpectedFailure', ...
        'Mapped Step 9.4 unexpectedly accepted an invalid admitted identity match.');
catch ME
    diary off;
    if ME.identifier == "TEST:ExpectedFailure"
        rethrow(ME);
    end
    assert(ME.identifier == expectedIdentifier, ...
        'Mapped Step 9.4 used the wrong identity-match error: %s', ...
        ME.identifier);
    diagnostic = lower(string(ME.message));
    for token = lower(string(privateTokens))
        assert(~contains(diagnostic, token), ...
            'Mapped Step 9.4 exposed a private source component in its error.');
    end
end

assert(strcmp(fileread(outputPath), acceptedOutputText), ...
    'Rejected mapped Step 9.4 replaced its accepted CSV.');
logPath = fullfile(root, 'data', 'logs', ...
    'step_9_jasp_4_data_prep_other.log');
assert(isfile(logPath), 'Rejected mapped Step 9.4 did not create its diary.');
logText = lower(string(fileread(logPath)));
for token = lower(string(privateTokens))
    assert(~contains(logText, token), ...
