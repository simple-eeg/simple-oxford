mkdir(scriptsRoot);
mkdir(functionsRoot);
mkdir(screeningRoot);
mkdir(dataListsRoot);
mkdir(resultsRoot);
mkdir(fullfile(temporaryRoot, 'data', 'raw'));

step8Artifacts = { ...
    'figure_3_post_core_guardrails_in_the_petal_dataset.pdf', ...
    'supplementary_table_1_petal_dataset_characteristics.csv', ...
    ['supplementary_table_4_nrf_template_derivation_and_' ...
        'fitting_details.csv'], ...
    'supplementary_figure_1_nrf_template_visualisations.pdf'};
