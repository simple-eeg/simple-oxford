    observedSentinel = fileread(fullfile( ...
        resultsRoot, step8Artifacts{artifactIndex}));
    assert(strcmp(observedSentinel, step8Sentinels{artifactIndex}), ...
        'Step 9 changed a Step 8 result: %s', ...
        step8Artifacts{artifactIndex});
end

expectedLogs = { ...
    'step_9_jasp_1_data_prep_eeg_qc.log', ...
    'step_9_jasp_2_data_prep_eeg_nrf.log', ...
    'step_9_jasp_3_data_prep_eeg_combine.log', ...
