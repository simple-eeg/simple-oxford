function tf = value_contains_token(value, token)
tf = false;
if ischar(value) || isstring(value) || iscategorical(value)
    tf = any(contains(lower(string(value)), lower(string(token))), 'all');
elseif iscell(value)
    for valueIndex = 1:numel(value)
        if value_contains_token(value{valueIndex}, token)
            tf = true;
            return;
        end
    end
elseif istable(value)
    for variableIndex = 1:width(value)
        variableName = value.Properties.VariableNames{variableIndex};
        if value_contains_token(value.(variableName), token)
            tf = true;
            return;
        end
    end
elseif isstruct(value)
    fields = fieldnames(value);
    for elementIndex = 1:numel(value)
        for fieldIndex = 1:numel(fields)
            if value_contains_token(value(elementIndex).(fields{fieldIndex}), token)
                tf = true;
                return;
            end
        end
    end
end
end

