    'step_9_jasp_6_add_bvt_cols.log'};
logRoot = fullfile(temporaryRoot, 'data', 'logs');
assert(isequal(sorted_file_names(logRoot, '*'), expectedLogs));
expectedMessages = { ...
    'Wrote Step 9.1 intermediate:', ...
    'Wrote Step 9.2 intermediate:', ...
    'Wrote Step 9.3 intermediate:', ...
    'Wrote Step 9.4 intermediate:', ...
    'Wrote Step 9.5 provisional table:', ...
    'Finalised Step 9 JASP table:'};
for logIndex = 1:numel(expectedLogs)
    logText = fileread(fullfile(logRoot, expectedLogs{logIndex}));
    assert(contains(logText, expectedMessages{logIndex}), ...
        'Step 9 success log lacks its completion message: %s', ...
        expectedLogs{logIndex});
