function assert_raw_subject_ids(filePath, expectedIDs)
text = string(fileread(filePath));
for expectedID = expectedIDs
    expression = "(?m)^" + expectedID + ",";
    assert(~isempty(regexp(char(text), char(expression), 'once')), ...
        'CSV did not retain exact raw subjectID lexeme %s: %s', ...
        expectedID, filePath);
end
end

function names = sorted_file_names(folder, pattern)
