function passed = run_failure_case(repoRoot, mode)
[root, cleanup] = make_fixture(repoRoot, mode); %#ok<ASGLU>
before = snapshot_regular_files(root);
scriptPath = fullfile(root, 'scripts', ...
    'step_9_gen_2_sample_details.m');

try
    run_fixture_script(scriptPath);
    error('TEST:ExpectedFailure', ...
        'Step 9.2 unexpectedly accepted the %s fixture.', mode);
catch ME
    if ME.identifier == "TEST:ExpectedFailure"
        rethrow(ME);
    end
    if mode == "incomplete"
        assert(ME.identifier == "SimpleOxford:SampleDetails:IncompleteData", ...
            'Step 9.2 used the wrong incomplete-data error: %s', ...
            ME.identifier);
    else
        assert(ME.identifier == "SimpleOxford:SampleDetails:UnexpectedCategory", ...
            'Step 9.2 used the wrong category error: %s', ME.identifier);
    end
end

after = snapshot_regular_files(root);
assert(isequal(before, after), ...
    'A rejected Step 9.2 fixture changed the file inventory.');
assert(~isfolder(fullfile(root, 'data', 'logs')), ...
    'A rejected Step 9.2 fixture created a log directory.');
assert(~isfolder(fullfile(root, 'data', 'jasp')), ...
    'A rejected Step 9.2 fixture created the retired data/jasp directory.');
passed = 1;
end

